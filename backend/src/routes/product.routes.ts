import { Router } from "express";
import { requireAuth } from "../middleware/auth.js";
import { auditMutation } from "../middleware/activityAudit.js";
import { requirePermission } from "../security/permissions.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import { createProduct, deactivateProduct, listProducts, updateProduct, receiveBatch, recordMovement, listInventory } from "../controllers/product.controller.js";
export const productRouter = Router();
productRouter.use(requireAuth);
productRouter.get("/", requirePermission("products.view"), asyncHandler(listProducts));
productRouter.get("/inventory", requirePermission("inventory.view"), asyncHandler(listInventory));
productRouter.post("/", auditMutation("PRODUCT_CREATED", "PRODUCT"), requirePermission("products.manage"), asyncHandler(createProduct));
productRouter.post("/batches", auditMutation("INVENTORY_RECEIVED", "INVENTORY"), requirePermission("inventory.manage"), asyncHandler(receiveBatch));
productRouter.post("/movements", auditMutation("INVENTORY_CHANGED", "INVENTORY"), requirePermission("inventory.manage"), asyncHandler(recordMovement));
productRouter.put("/:id", auditMutation("PRODUCT_UPDATED", "PRODUCT"), requirePermission("products.manage"), asyncHandler(updateProduct));
productRouter.delete("/:id", auditMutation("PRODUCT_DELETED", "PRODUCT"), requirePermission("products.manage"), asyncHandler(deactivateProduct));
